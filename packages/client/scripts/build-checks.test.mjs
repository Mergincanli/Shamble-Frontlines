test("the glue stays in the Worker's chunk, and development code stays out of a production build", () => {
  const file = (name, text) => ({ name, bytes: Buffer.from(text) });
  const worker = file("assets/worker-abc.js", "wasm.__wbindgen_malloc(1); imports.__wbg_Error_1 = 0;");
  const page = file("assets/index-abc.js", "boot()");
  const dev = file("assets/report-abc.js", 'x("Copy report", window.__shambleReport, "ticks while hidden", "first page: report", "key-diagram")');
  const entry = worker.name;
  expect(bundleProblems([worker, page], true, entry)).toEqual([]);
  expect(bundleProblems([worker, page, dev], false, entry)).toEqual([]);
  expect(bundleProblems([worker, file("assets/index-abc.js", "__wbg_init()")], true, entry)).toEqual([
    "assets/index-abc.js: the Wasm's glue outside the Worker's chunk",
  ]);
  expect(bundleProblems([worker, file("assets/index-abc.js", "WebAssembly.validate(b)")], true, entry)).toEqual([
    "assets/index-abc.js: the page's code names WebAssembly",
  ]);
  expect(bundleProblems([worker, page, dev], true, entry)).toHaveLength(5);
  expect(bundleProblems([worker, page], false, entry)).toHaveLength(5);
  // A page module whose file is named like the Worker's (a part of the page loaded later, split off from
  // app/worker-link.ts) is the page's all the same: the Worker's chunk is the one the build named, and no other.
  const lookalike = file("assets/worker-link-abc.js", "WebAssembly.instantiate(bytes); wasm.__wbindgen_start();");
  expect(bundleProblems([worker, page, lookalike], true, entry)).toEqual([
    "assets/worker-link-abc.js: the Wasm's glue outside the Worker's chunk",
    "assets/worker-link-abc.js: the page's code names WebAssembly",
  ]);
  // Without the Worker's chunk by name nothing can be told apart, and that is a refusal, not a pass.
  for (const missing of [undefined, "", "assets/worker-other.js", "worker-abc.js"]) {
    expect(bundleProblems([worker, page], true, missing), String(missing)).toEqual([
      expect.stringContaining("is not among the built scripts"),
    ]);
  }
});

test("the Worker's chunk is the one entry chunk the build made from the Worker's source module", () => {
  const source = "/repo/packages/sim-worker/src/worker.ts";
  const entry = { fileName: "assets/worker-abc.js", isEntry: true, facadeModuleId: source };
  const split = { fileName: "assets/stats-abc.js", isEntry: false, facadeModuleId: "/repo/packages/sim-worker/src/stats.ts" };
  expect(workerEntryChunk([entry], source)).toBe("assets/worker-abc.js");
  expect(workerEntryChunk([split, entry], source)).toBe("assets/worker-abc.js");
  // The module's address may carry a query, and Windows writes the path with other slashes.
  expect(workerEntryChunk([{ ...entry, facadeModuleId: `${source}?worker_file&type=module` }], source)).toBe("assets/worker-abc.js");
  expect(workerEntryChunk([{ ...entry, facadeModuleId: "C:/repo/packages/sim-worker/src/worker.ts" }], "C:\\repo\\packages\\sim-worker\\src\\worker.ts")).toBe(
    "assets/worker-abc.js",
  );
  // No such chunk, two of them, a chunk of that module that is no entry, or an entry of another module: refused.
  expect(() => workerEntryChunk([], source)).toThrow("made 0 entry chunks");
  expect(() => workerEntryChunk([split], source)).toThrow("made 0 entry chunks");
  expect(() => workerEntryChunk([{ ...entry, isEntry: false }], source)).toThrow("made 0 entry chunks");
  expect(() => workerEntryChunk([{ ...entry, facadeModuleId: null }], source)).toThrow("made 0 entry chunks");
  expect(() => workerEntryChunk([{ ...entry, facadeModuleId: "/repo/packages/client/src/app/worker-link.ts" }], source)).toThrow("made 0 entry chunks");
  expect(() => workerEntryChunk([entry, { ...entry, fileName: "assets/worker-def.js" }], source)).toThrow("made 2 entry chunks");
});

test("a built page holds the players' WebAssembly and no other", () => {
  const players = Buffer.from([0x00, 0x61, 0x73, 0x6d, 1, 0, 0, 0, 7]);
  const other = Buffer.from([0x00, 0x61, 0x73, 0x6d, 1, 0, 0, 0, 8]);
  const page = [{ name: "index.html", bytes: Buffer.from("<!doctype html>") }, { name: "assets/index-abc.js", bytes: Buffer.from("boot()") }];
  const own = { name: "assets/sim_wasm_bg-abc.wasm", bytes: players };
  expect(wasmProblems([...page, own], players)).toEqual([]);
  // A second copy of the players' own file is the same file; a Uint8Array is compared as a Buffer is.
  expect(wasmProblems([...page, own, { name: "assets/copy.wasm", bytes: new Uint8Array(players) }], new Uint8Array(players))).toEqual([]);
  // The test-only module beside it, whatever it is called: by its name's ending, or by its first bytes alone.
  expect(wasmProblems([...page, own, { name: "assets/devtools_bg.wasm", bytes: other }], players)).toEqual([
    "assets/devtools_bg.wasm: a WebAssembly file that is not the players' own",
  ]);
  expect(wasmProblems([...page, own, { name: "assets/data.bin", bytes: other }], players)).toEqual([
    "assets/data.bin: a WebAssembly file that is not the players' own",
  ]);
  expect(wasmProblems([...page, own, { name: "empty.wasm", bytes: Buffer.alloc(0) }], players)).toEqual([
    "empty.wasm: a WebAssembly file that is not the players' own",
  ]);
  // Another file in the players' place, and no WebAssembly at all, are both refused.
  expect(wasmProblems([...page, { ...own, bytes: other }], players)).toEqual([
    "assets/sim_wasm_bg-abc.wasm: a WebAssembly file that is not the players' own",
    "no file is the players' WebAssembly: the Worker would have nothing to load",
  ]);
  expect(wasmProblems(page, players)).toEqual(["no file is the players' WebAssembly: the Worker would have nothing to load"]);
});

