import { createHash } from "node:crypto";
import { mkdtempSync, rmSync, symlinkSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { afterAll, beforeAll, describe, expect, test } from "vitest";
import {
  checkCli,
  checkCliFile,
  formatSizeTable,
  lockedWasmBindgenVersion,
  MAX_SERVED_BYTES,
  sizeTable,
  tooLarge,
} from "./build-checks.mjs";

const LOCK = `# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "sim-wasm"
version = "0.0.0"
dependencies = [
 "wasm-bindgen",
]

[[package]]
name = "wasm-bindgen"
version = "0.2.130"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "a0181c14"
dependencies = [
 "cfg-if",
 "wasm-bindgen-macro",
]

[[package]]
name = "wasm-bindgen-macro"
version = "0.2.130"
source = "registry+https://github.com/rust-lang/crates.io-index"
`;

describe("the version in Cargo.lock", () => {
  test("is read from the wasm-bindgen entry, not from a crate whose name starts the same", () => {
    expect(lockedWasmBindgenVersion(LOCK)).toBe("0.2.130");
    expect(lockedWasmBindgenVersion(LOCK.replace('"0.2.130"\nsource', '"0.2.129"\nsource'))).toBe("0.2.129");
  });

  test("no entry, or two, stops the build", () => {
    expect(() => lockedWasmBindgenVersion("version = 4\n")).toThrow("found 0");
    expect(() => lockedWasmBindgenVersion(LOCK.replace('name = "wasm-bindgen-macro"', 'name = "wasm-bindgen"'))).toThrow(
      "found 2",
    );
  });
});

describe("the tool's version against the lock", () => {
  test("equal versions pass", () => {
    expect(() => checkCli("wasm-bindgen 0.2.130\n", "0.2.130")).not.toThrow();
  });

  test("a tool one patch off is refused, with both versions named", () => {
    expect(() => checkCli("wasm-bindgen 0.2.129\n", "0.2.130")).toThrow(/0\.2\.129.*0\.2\.130/);
    expect(() => checkCli("wasm-bindgen 0.2.131", "0.2.130")).toThrow(/0\.2\.131/);
  });

  test("output that is not a version line is refused", () => {
    for (const output of ["", "wasm-bindgen", "0.2.130", "wasm-bindgen 0.2", "wasm-bindgen-cli 0.2.130", "wasm-bindgen 0.2.130 (abc)"]) {
      expect(() => checkCli(output, "0.2.130"), output).toThrow("no version this script can read");
    }
  });
});

describe("the tool's file before any run", () => {
  let folder;
  let tool;
  const content = Buffer.from("#!/bin/sh\necho wasm-bindgen 0.2.130\n");
  const sha256 = createHash("sha256").update(content).digest("hex");

  beforeAll(() => {
    folder = mkdtempSync(path.join(tmpdir(), "shamble-build-checks-"));
    tool = path.join(folder, "wasm-bindgen");
    writeFileSync(tool, content);
  });
  afterAll(() => rmSync(folder, { recursive: true, force: true }));

  test("the recorded size and sha256 pass", () => {
    expect(() => checkCliFile(tool, sha256, content.length)).not.toThrow();
  });

  test("another sha256 or another size is refused", () => {
    const other = sha256.replace(/^./, sha256.startsWith("0") ? "1" : "0");
    expect(() => checkCliFile(tool, other, content.length)).toThrow("not the recorded one");
    expect(() => checkCliFile(tool, sha256, content.length + 1)).toThrow("not the recorded");
  });

  test("missing expected values are refused: the tool is never run uncompared", () => {
    for (const expected of [undefined, "", "abc", sha256.toUpperCase(), `${sha256}0`]) {
      expect(() => checkCliFile(tool, expected, content.length), String(expected)).toThrow("expected sha256 is not given");
    }
    for (const size of [undefined, 0, -1, 1.5]) {
      expect(() => checkCliFile(tool, sha256, size), String(size)).toThrow("expected size is not given");
    }
  });

  test("a link to the right file is refused", () => {
    const link = path.join(folder, "link");
    try {
      symlinkSync(tool, link);
    } catch {
      return; // a system that does not let this user make links
    }
    expect(() => checkCliFile(link, sha256, content.length)).toThrow("not a plain file");
  });

  test("a file that is not there is refused", () => {
    expect(() => checkCliFile(path.join(folder, "missing"), sha256, content.length)).toThrow();
  });
});

describe("the size table", () => {
  const compressible = Buffer.alloc(100_000, "shamble ");
  const rows = sizeTable([
    { name: "sim_wasm_bg.wasm", bytes: compressible },
    { name: "tiny.js", bytes: Buffer.from("x") },
  ]);

  test("gives each file's size raw, with gzip and with Brotli", () => {
    expect(rows.map((row) => row.name)).toEqual(["sim_wasm_bg.wasm", "tiny.js"]);
    expect(rows[0].raw).toBe(100_000);
    expect(rows[0].gzip).toBeLessThan(1000);
    expect(rows[0].brotli).toBeLessThan(rows[0].gzip);
    expect(rows[1].raw).toBe(1);
  });

  test("prints one line per file under a heading", () => {
    const lines = formatSizeTable(rows).split("\n");
    expect(lines).toHaveLength(3);
    expect(lines[0]).toMatch(/^file\s+raw\s+gzip -9\s+brotli 11$/);
    expect(lines[1]).toMatch(/^sim_wasm_bg\.wasm\s+100000\s+\d+\s+\d+$/);
  });

  test("a file that reaches 25 MiB is named; one byte less is not", () => {
    expect(MAX_SERVED_BYTES).toBe(25 * 1024 * 1024);
    const atLimit = { name: "big.wasm", raw: MAX_SERVED_BYTES, gzip: 1, brotli: 1 };
    const under = { name: "ok.wasm", raw: MAX_SERVED_BYTES - 1, gzip: 1, brotli: 1 };
    expect(tooLarge([atLimit, under])).toEqual([atLimit]);
    expect(tooLarge(rows)).toEqual([]);
  });
});
