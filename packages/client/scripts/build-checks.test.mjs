const LOCK = `# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "sim-wasm"
version = "0.0.0"
dependencies = [
 "wasm-bindgen",
]

[[package]]
name = "wasm-bindgen"
version = "0.2.130"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "a0181c14"
dependencies = [
 "cfg-if",
 "wasm-bindgen-macro",
]

[[package]]
name = "wasm-bindgen-macro"
version = "0.2.130"
source = "registry+https://github.com/rust-lang/crates.io-index"
`;

describe("the version in Cargo.lock", () => {
  test("is read from the wasm-bindgen entry, not from a crate whose name starts the same", () => {
    expect(lockedWasmBindgenVersion(LOCK)).toBe("0.2.130");
    expect(lockedWasmBindgenVersion(LOCK.replace('"0.2.130"\nsource', '"0.2.129"\nsource'))).toBe("0.2.129");
  });

  test("no entry, or two, stops the build", () => {
    expect(() => lockedWasmBindgenVersion("version = 4\n")).toThrow("found 0");
    expect(() => lockedWasmBindgenVersion(LOCK.replace('name = "wasm-bindgen-macro"', 'name = "wasm-bindgen"'))).toThrow(
      "found 2",
    );
  });
});

describe("the tool's version against the lock", () => {
  test("equal versions pass", () => {
    expect(() => checkCli("wasm-bindgen 0.2.130\n", "0.2.130")).not.toThrow();
  });

  test("a tool one patch off is refused, with both versions named", () => {
    expect(() => checkCli("wasm-bindgen 0.2.129\n", "0.2.130")).toThrow(/0\.2\.129.*0\.2\.130/);
    expect(() => checkCli("wasm-bindgen 0.2.131", "0.2.130")).toThrow(/0\.2\.131/);
  });

  test("output that is not a version line is refused", () => {
    for (const output of ["", "wasm-bindgen", "0.2.130", "wasm-bindgen 0.2", "wasm-bindgen-cli 0.2.130", "wasm-bindgen 0.2.130 (abc)"]) {
      expect(() => checkCli(output, "0.2.130"), output).toThrow("no version this script can read");
    }
  });
});

describe("the tool's file before any run", () => {
  let folder;
  let tool;
  const content = Buffer.from("#!/bin/sh\necho wasm-bindgen 0.2.130\n");
  const sha256 = createHash("sha256").update(content).digest("hex");

  beforeAll(() => {
    folder = mkdtempSync(path.join(tmpdir(), "shamble-build-checks-"));
    tool = path.join(folder, "wasm-bindgen");
    writeFileSync(tool, content);
  });
  afterAll(() => rmSync(folder, { recursive: true, force: true }));

  test("the recorded size and sha256 pass", () => {
    expect(() => checkCliFile(tool, sha256, content.length)).not.toThrow();
  });

  test("another sha256 or another size is refused", () => {
    const other = sha256.replace(/^./, sha256.startsWith("0") ? "1" : "0");
    expect(() => checkCliFile(tool, other, content.length)).toThrow("not the recorded one");
    expect(() => checkCliFile(tool, sha256, content.length + 1)).toThrow("not the recorded");
  });

  test("missing expected values are refused: the tool is never run uncompared", () => {
    for (const expected of [undefined, "", "abc", sha256.toUpperCase(), `${sha256}0`]) {
      expect(() => checkCliFile(tool, expected, content.length), String(expected)).toThrow("expected sha256 is not given");
    }
    for (const size of [undefined, 0, -1, 1.5]) {
      expect(() => checkCliFile(tool, sha256, size), String(size)).toThrow("expected size is not given");
    }
  });

  test("a link to the right file is refused", () => {
    const link = path.join(folder, "link");
    try {
      symlinkSync(tool, link);
    } catch {
      return; // a system that does not let this user make links
    }
    expect(() => checkCliFile(link, sha256, content.length)).toThrow("not a plain file");
  });

  test("a file that is not there is refused", () => {
    expect(() => checkCliFile(path.join(folder, "missing"), sha256, content.length)).toThrow();
  });
});

describe("the size table", () => {
  const compressible = Buffer.alloc(100_000, "shamble ");
  const rows = sizeTable([
    { name: "sim_wasm_bg.wasm", bytes: compressible },
    { name: "tiny.js", bytes: Buffer.from("x") },
  ]);

  test("gives each file's size raw, with gzip and with Brotli", () => {
    expect(rows.map((row) => row.name)).toEqual(["sim_wasm_bg.wasm", "tiny.js"]);
    expect(rows[0].raw).toBe(100_000);
    expect(rows[0].gzip).toBeLessThan(1000);
    expect(rows[0].brotli).toBeLessThan(rows[0].gzip);
    expect(rows[1].raw).toBe(1);
  });

  test("prints one line per file under a heading", () => {
    const lines = formatSizeTable(rows).split("\n");
    expect(lines).toHaveLength(3);
    expect(lines[0]).toMatch(/^file\s+raw\s+gzip -9\s+brotli 11$/);
    expect(lines[1]).toMatch(/^sim_wasm_bg\.wasm\s+100000\s+\d+\s+\d+$/);
  });

  test("a file that reaches 25 MiB is named; one byte less is not", () => {
    expect(MAX_SERVED_BYTES).toBe(25 * 1024 * 1024);
    const atLimit = { name: "big.wasm", raw: MAX_SERVED_BYTES, gzip: 1, brotli: 1 };
    const under = { name: "ok.wasm", raw: MAX_SERVED_BYTES - 1, gzip: 1, brotli: 1 };
    expect(tooLarge([atLimit, under])).toEqual([atLimit]);
    expect(tooLarge(rows)).toEqual([]);
  });
});

describe("the page stays ready for a strict content security policy", () => {
  const file = (name, text) => ({ name, bytes: Buffer.from(text) });
  const good = [
    file("index.html", '<!doctype html><link rel="stylesheet" href="./assets/a.css"><script type="module" src="./assets/a.js"></script>'),
    file("assets/a.js", 'new Worker(new URL("./worker-abc.js", import.meta.url), { type: "module" }); const style = "x"; onload = 1;'),
    file("assets/sim_wasm_bg.wasm", "data:application/wasm is only text inside a binary here"),
  ];

  test("a page whose scripts, styles, Worker and Wasm are all files passes", () => {
    expect(cspProblems(good)).toEqual([]);
  });

  test("each way to break it is named", () => {
    const bad = {
      "an inline script": file("index.html", "<script>boot()</script>"),
      "an inline style element": file("index.html", "<style>body{}</style>"),
      "a style attribute": file("index.html", '<p style="color:red">x</p>'),
      "an inline event handler": file("index.html", '<body onload="boot()">'),
      "a script or the Wasm in a data: URL": file("assets/a.js", 'fetch("data:application/wasm;base64,AGFzbQ==")'),
      "a blob: URL": file("assets/b.js", "const u = URL.createObjectURL(blob); new Worker(u)"),
      eval: file("assets/c.js", "x = eval(source)"),
      "new Function": file("assets/d.js", "f = new Function(body)"),
    };
    for (const [problem, broken] of Object.entries(bad)) {
      expect(cspProblems([...good, broken]), problem).toEqual([`${broken.name}: ${problem}`]);
    }
  });
});

test("the build empties only its own dist or a folder named dist-<something>", () => {
  const own = "/repo/packages/client/dist";
  for (const good of [own, "/repo/.gate/cs2/dist-prod", "/tmp/dist-1.2"]) expect(() => checkOutDir(good, own)).not.toThrow();
  for (const bad of ["/repo", "/repo/.gate", "/repo/packages/client/src", "/repo/packages/client/dist2", "/repo/dist-", "/"]) {
    expect(() => checkOutDir(bad, own), bad).toThrow("because the build empties it");
  }
});

test("the glue stays in the Worker's chunk, and development code stays out of a production build", () => {
  const file = (name, text) => ({ name, bytes: Buffer.from(text) });
  const worker = file("assets/worker-abc.js", "wasm.__wbindgen_malloc(1); imports.__wbg_Error_1 = 0;");
  const page = file("assets/index-abc.js", "boot()");
  const dev = file("assets/report-abc.js", 'x("Copy report", window.__shambleReport, "ticks while hidden", "first page: report")');
  expect(bundleProblems([worker, page], true)).toEqual([]);
  expect(bundleProblems([worker, page, dev], false)).toEqual([]);
  expect(bundleProblems([worker, file("assets/index-abc.js", "__wbg_init()")], true)).toEqual([
    "assets/index-abc.js: the Wasm's glue outside the Worker's chunk",
  ]);
  expect(bundleProblems([worker, file("assets/index-abc.js", "WebAssembly.validate(b)")], true)).toEqual([
    "assets/index-abc.js: the page's code names WebAssembly",
  ]);
  expect(bundleProblems([worker, page, dev], true)).toHaveLength(4);
  expect(bundleProblems([worker, page], false)).toHaveLength(4);
});

test("the Wasm build refuses cargo's and the tool's settings from the environment, and lets the build folder and CI's names through", () => {
  // One name per family of the pattern; the last two: a build-folder name with more after it is refused.
  const refused = [
    "RUSTFLAGS", "CARGO_ENCODED_RUSTFLAGS", "RUSTC", "RUSTC_WRAPPER", "RUSTC_WORKSPACE_WRAPPER", "RUSTUP_TOOLCHAIN",
    "CARGO_BUILD_RUSTFLAGS", "CARGO_BUILD_TARGET", "CARGO_PROFILE_RELEASE_OVERFLOW_CHECKS", "CARGO_PROFILE_RELEASE_OPT_LEVEL",
    "CARGO_RESOLVER_LOCKFILE_PATH", "CARGO_INCREMENTAL", "RUSTC_BOOTSTRAP",
    "CARGO_TARGET_WASM32_UNKNOWN_UNKNOWN_RUSTFLAGS", "WASM_BINDGEN_KEEP_DEBUG", "RUST_LOG", "CARGO_TARGET_DIR_X",
    "CARGO_BUILD_TARGET_DIRX",
  ];
  // The two build-folder names (the build's --target-dir beats them), every name CI's network cut sets (toolchain.yml,
  // its env -i list, with the tool's path), and two names that only contain a refused one.
  const allowed = [
    "CARGO_TARGET_DIR", "CARGO_BUILD_TARGET_DIR", "HOME", "PATH", "USER", "CI", "LANG", "PROBE_IP", "CARGO_HOME",
    "RUSTUP_HOME", "RUSTUP_AUTO_INSTALL", "npm_config_update_notifier", "SHAMBLE_WASM_BINDGEN", "XRUSTFLAGS", "RUSTFLAGS_X",
  ];
  const env = Object.fromEntries([...allowed, ...refused].map((name) => [name, "x"]));
  expect(refusedBuildSettings(env)).toEqual(refused);
  expect(refusedBuildSettings({})).toEqual([]);
});

