    expect(simFeatureList(`0dep v0.0.0 (/repo/crates/dep)\n\n${PLAYERS}\n0sim v0.0.0 (/repo/crates/sim)\n1dep feature "default" (command-line)\n2dep v0.0.0 (/repo/crates/dep)\n`)).toEqual(plain);
