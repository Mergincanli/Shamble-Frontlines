//! Our own small generator (ADR 0002 part 5): it prints the block's layout table as TypeScript for `packages/types`.
//! Test builds only. The export test fails when the committed file is not what the table gives; to write the file
//! again: `SHAMBLE_WRITE_TYPES=1 cargo test -p client-endpoint`.

use crate::layout::{BLOCK_LAYOUT, LAYOUT_HASH, Section};
use std::fmt::Write as _;
use std::fs;
use std::path::Path;

const GENERATED_FOLDER: &str = "packages/types/src/generated/block";
const FILE_NAME: &str = "layout.ts";

/// The text of `layout.ts`: the hash, then per section its stride, its alignment (its largest field) and its fields.
fn render_typescript(sections: &[Section], hash: u32) -> String {
    let mut out = String::from(
        "// Generated by the test generated_layout_is_current from the table in\n\
         // crates/client-endpoint/src/layout.rs. Do not edit. To write it again:\n\
         // SHAMBLE_WRITE_TYPES=1 cargo test -p client-endpoint\n\n",
    );
    writeln!(out, "export const LAYOUT_HASH = 0x{hash:08x};").expect("a String takes every write");
    for section in sections {
        let sizes = section.fields.iter().map(|field| field.ty.size());
        let (name, stride, align) = (section.name, section.stride, sizes.max().unwrap_or(1));
        write!(
            out,
            "\nexport const {name} = {{\n  stride: {stride},\n  align: {align},\n  fields: {{\n"
        )
        .expect("a String takes every write");
        for field in section.fields {
            let (name, offset, ty) = (field.name, field.offset, field.ty.name());
            writeln!(out, "    {name}: {{ offset: {offset}, type: \"{ty}\" }},")
                .expect("a String takes every write");
        }
        out.push_str("  },\n} as const;\n");
    }
    out
}

/// Write mode: clears the generated folder of its `.ts` files (only those directly in it) and writes the file.
fn write_generated(folder: &Path, text: &str) {
    assert!(
        folder.ends_with(GENERATED_FOLDER),
        "write mode only writes into {GENERATED_FOLDER}"
    );
    fs::create_dir_all(folder).expect("the generated folder can be made");
    for entry in fs::read_dir(folder).expect("the generated folder can be read") {
        let entry = entry.expect("its entries can be read");
        // A link counts as a file here: it is deleted, never followed.
        let is_folder = entry.file_type().is_ok_and(|kind| kind.is_dir());
        if !is_folder && entry.path().extension().is_some_and(|ext| ext == "ts") {
            fs::remove_file(entry.path()).expect("an old generated file can be deleted");
        }
    }
    fs::write(folder.join(FILE_NAME), text).expect("the generated file can be written");
}

#[test]
fn generated_layout_is_current() {
    let folder = Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../..")
        .join(GENERATED_FOLDER);
    let expected = render_typescript(BLOCK_LAYOUT, LAYOUT_HASH);
    if std::env::var_os("SHAMBLE_WRITE_TYPES").is_some_and(|value| value == "1") {
        write_generated(&folder, &expected);
    }
    let how = "write it again with SHAMBLE_WRITE_TYPES=1 cargo test -p client-endpoint";
    let mut names: Vec<String> = fs::read_dir(&folder)
        .unwrap_or_else(|error| panic!("{GENERATED_FOLDER} cannot be read ({error}); {how}"))
        .map(|entry| {
            entry
                .expect("its entries can be read")
                .file_name()
                .to_string_lossy()
                .into_owned()
        })
        .collect();
    names.sort();
    assert_eq!(
        names,
        [FILE_NAME],
        "{GENERATED_FOLDER} must hold {FILE_NAME} and nothing else; {how}"
    );
    let committed =
        fs::read_to_string(folder.join(FILE_NAME)).expect("the generated file can be read");
    assert!(
        committed == expected,
        "{GENERATED_FOLDER}/{FILE_NAME} is not what the layout table gives; {how}\n\
         --- the committed file\n{committed}\n--- from the table\n{expected}"
    );
}

#[test]
fn typescript_carries_the_hash() {
    use crate::layout::{ElementType, Field};

    // The real table: the number in the text, read back, is the Rust constant.
    let text = render_typescript(BLOCK_LAYOUT, LAYOUT_HASH);
    let line = text
        .lines()
        .find(|line| line.starts_with("export const LAYOUT_HASH = "))
        .expect("a hash line");
    let hex = line
        .trim_start_matches("export const LAYOUT_HASH = 0x")
        .trim_end_matches(';');
    assert_eq!(u32::from_str_radix(hex, 16), Ok(LAYOUT_HASH));

    // A small table, whole: a short hash keeps its eight digits, and the alignment is the largest field's size.
    #[rustfmt::skip]
    let table = [
        Section { name: "one", stride: 1, fields: &[
            Field { name: "a",   ty: ElementType::U8,  offset: 0 },
        ] },
        Section { name: "two", stride: 8, fields: &[
            Field { name: "b",   ty: ElementType::U32, offset: 0 },
            Field { name: "c_2", ty: ElementType::U8,  offset: 4 },
        ] },
    ];
    let text = render_typescript(&table, 0xab);
    let body = text
        .split_once("\n\n")
        .expect("a blank line after the comment")
        .1;
    let expected = r#"export const LAYOUT_HASH = 0x000000ab;

export const one = {
  stride: 1,
  align: 1,
  fields: {
    a: { offset: 0, type: "u8" },
  },
} as const;

export const two = {
  stride: 8,
  align: 4,
  fields: {
    b: { offset: 0, type: "u32" },
    c_2: { offset: 4, type: "u8" },
  },
} as const;
"#;
    assert_eq!(body, expected);
}
