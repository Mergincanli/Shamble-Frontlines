//! Our own small generator (ADR 0002 part 5): it prints the block's layout table as TypeScript for `packages/types`.
//! Test builds only. The export test fails when the committed file is not what the table gives; to write the file
//! again: `SHAMBLE_WRITE_TYPES=1 cargo test -p client-endpoint`.

use crate::layout::{BLOCK_LAYOUT, Field, LAYOUT_HASH, Section};
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

const GENERATED_FOLDER: &str = "packages/types/src/generated/block";
const FILE_NAME: &str = "layout.ts";

/// The text of `layout.ts`: the hash, then one object that holds, per section, its stride and its fields.
fn render_typescript(sections: &[Section], hash: u32) -> String {
    let mut out = String::from(
        "// Generated by the test generated_layout_is_current from the table in\n\
         // crates/client-endpoint/src/layout.rs. Do not edit. To write it again:\n\
         // SHAMBLE_WRITE_TYPES=1 cargo test -p client-endpoint\n\n",
    );
    writeln!(out, "export const LAYOUT_HASH = 0x{hash:08x};").expect("a String takes every write");
    out.push_str("\nexport const BLOCK_LAYOUT = {\n");
    // Every member is named in these two patterns, as in `layout_hash`: this file states nothing the hash leaves out.
    for &Section {
        name,
        stride,
        fields,
    } in sections
    {
        write!(out, "  {name}: {{\n    stride: {stride},\n    fields: {{\n")
            .expect("a String takes every write");
        for &Field { name, ty, offset } in fields {
            let ty = ty.name();
            writeln!(out, "      {name}: {{ offset: {offset}, type: \"{ty}\" }},")
                .expect("a String takes every write");
        }
        out.push_str("    },\n  },\n");
    }
    out.push_str("} as const;\n");
    out
}

/// The repository's root, from the folder `cargo test` runs this crate in. A test binary built in another copy of the
/// repository (two copies sharing one target folder) is stopped here: it would check and write that other copy.
fn repository_root() -> PathBuf {
    let built_in = env!("CARGO_MANIFEST_DIR");
    let run_in = std::env::var("CARGO_MANIFEST_DIR").ok();
    assert_eq!(
        run_in.as_deref(),
        Some(built_in),
        "run this test through cargo test, from the copy of the repository it was built in ({built_in}), with a \
         target folder that no other copy shares"
    );
    Path::new(built_in).join("../..")
}

/// Write mode: deletes the generated folder's `.ts` entries (only those directly in it; a link is deleted, never
/// followed) and writes the file. It makes that one folder if it is missing, and nothing above it; it refuses a
/// path with a link in it, so it never writes outside the repository.
fn write_generated(root: &Path, text: &str) {
    let root = fs::canonicalize(root).expect("the repository's root can be resolved");
    let folder = root.join(GENERATED_FOLDER);
    let parent = folder.parent().expect("the generated folder has a parent");
    let unlinked = |path: &Path| fs::canonicalize(path).is_ok_and(|real| real == path);
    assert!(
        unlinked(parent),
        "write mode needs {} to exist, with no link in its path",
        parent.display()
    );
    if fs::symlink_metadata(&folder).is_err() {
        fs::create_dir(&folder).expect("the generated folder can be made");
    }
    assert!(
        unlinked(&folder),
        "write mode refuses {GENERATED_FOLDER}: it is a link"
    );
    for entry in fs::read_dir(&folder).expect("the generated folder can be read") {
        let entry = entry.expect("its entries can be read");
        let is_folder = entry.file_type().is_ok_and(|kind| kind.is_dir());
        if !is_folder && entry.path().extension().is_some_and(|ext| ext == "ts") {
            fs::remove_file(entry.path()).expect("an old generated file can be deleted");
        }
    }
    fs::write(folder.join(FILE_NAME), text).expect("the generated file can be written");
}

/// The entries directly in a folder, sorted: each name, and whether it is a plain file (not a folder, not a link).
fn entries_of(folder: &Path, how: &str) -> Vec<(String, bool)> {
    let shown = folder.display();
    let entries = fs::read_dir(folder)
        .unwrap_or_else(|error| panic!("{shown} cannot be read ({error}); {how}"));
    let mut found: Vec<(String, bool)> = entries
        .map(|entry| {
            let entry = entry.expect("its entries can be read");
            let plain = entry.file_type().is_ok_and(|kind| kind.is_file());
            (entry.file_name().to_string_lossy().into_owned(), plain)
        })
        .collect();
    found.sort();
    found
}

#[test]
fn generated_layout_is_current() {
    let root = repository_root();
    let expected = render_typescript(BLOCK_LAYOUT, LAYOUT_HASH);
    if std::env::var_os("SHAMBLE_WRITE_TYPES").is_some_and(|value| value == "1") {
        write_generated(&root, &expected);
    }
    let how = "delete by hand what does not belong there, then write the file again with \
               SHAMBLE_WRITE_TYPES=1 cargo test -p client-endpoint";
    let folder = root.join(GENERATED_FOLDER);
    assert_eq!(
        entries_of(&folder, how),
        [(FILE_NAME.to_owned(), true)],
        "{GENERATED_FOLDER} must hold the plain file {FILE_NAME} and nothing else; {how}"
    );
    let committed =
        fs::read_to_string(folder.join(FILE_NAME)).expect("the generated file can be read");
    assert!(
        committed == expected,
        "{GENERATED_FOLDER}/{FILE_NAME} is not what the layout table gives; {how}\n\
         --- the committed file\n{committed}\n--- from the table\n{expected}"
    );
    // The folder above belongs to the generators together: it holds their folders and no file of its own.
    let above = folder.parent().expect("the generated folder has a parent");
    let stray: Vec<String> = entries_of(above, how)
        .into_iter()
        .filter(|entry| entry.1)
        .map(|entry| entry.0)
        .collect();
    assert!(
        stray.is_empty(),
        "{} holds files of its own: {stray:?}; delete them by hand",
        above.display()
    );
}

#[test]
fn typescript_carries_the_hash() {
    use crate::layout::ElementType;

    // The real table: the number in the text, read back, is the Rust constant.
    let text = render_typescript(BLOCK_LAYOUT, LAYOUT_HASH);
    let line = text
        .lines()
        .find(|line| line.starts_with("export const LAYOUT_HASH = "))
        .expect("a hash line");
    let hex = line
        .trim_start_matches("export const LAYOUT_HASH = 0x")
        .trim_end_matches(';');
    assert_eq!(u32::from_str_radix(hex, 16), Ok(LAYOUT_HASH));

    // A small table, whole: a short hash keeps its eight digits; the sections keep their order.
    #[rustfmt::skip]
    let table = [
        Section { name: "one", stride: 1, fields: &[
            Field { name: "a",   ty: ElementType::U8,  offset: 0 },
        ] },
        Section { name: "two", stride: 8, fields: &[
            Field { name: "b",   ty: ElementType::U32, offset: 0 },
            Field { name: "c_2", ty: ElementType::U8,  offset: 4 },
        ] },
    ];
    let text = render_typescript(&table, 0xab);
    let body = text
        .split_once("\n\n")
        .expect("a blank line after the comment")
        .1;
    let expected = r#"export const LAYOUT_HASH = 0x000000ab;

export const BLOCK_LAYOUT = {
  one: {
    stride: 1,
    fields: {
      a: { offset: 0, type: "u8" },
    },
  },
  two: {
    stride: 8,
    fields: {
      b: { offset: 0, type: "u32" },
      c_2: { offset: 4, type: "u8" },
    },
  },
} as const;
"#;
    assert_eq!(body, expected);
}
